create table tq84_heartbeat_session (
   id         number generated by default as identity primary key,
   client_id  varchar2(50 char) not null,
   sid        number not null,
   serial#    number not null,
   client_ip  varchar2(64 char) not null
)
pctfree 0;

create table tq84_heartbeat_ping (
   id_session  number not null,
   dt          date,
   constraint tq84_heartbeat_ping_fk01 foreign key (id_session) references tq84_heartbeat_session (id)
)
pctfree 0;


create or replace trigger tq84_heartbeat_session_trg
   before insert on tq84_heartbeat_session
   for each row
declare
   l_serial number;
begin
  :new.sid       := to_number(sys_context('USERENV', 'SID'));
  :new.client_ip := sys_context('USERENV', 'IP_ADDRESS');

   execute immediate q'[
      select
         s.serial#
      from
         v$session s
      where
         s.audsid = sys_context('USERENV', 'SESSIONID')
         and rownum = 1
   ]'
   into l_serial;

  :new.serial# := l_serial;

end;
/

create or replace trigger tq84_heartbeat_ping_trg
   before insert on tq84_heartbeat_ping
   for each row
begin
  :new.dt := sysdate;
end;
/

create view tq84_heartbeat_v as
select
   ses.client_id,
   png.dt,
   ses.client_ip,
   ses.sid,
   ses.serial#,
   ses.id       session_id
from
   tq84_heartbeat_session ses                              join
   tq84_heartbeat_ping    png on ses.id = png.id_session;
